def tr(text):
    app = QApplication.instance()
    if app is None or app.property('solbreaker_language') != 'en':
        return text
    if text in ENGLISH:
        return ENGLISH[text]
    copy = COPY_PROGRESS.fullmatch(text)
    if copy:
        return f'Copying game resources — {copy[1]} of {copy[2]} MiB'
    for prefix, replacement in PREFIXES.items():
        if text.startswith(prefix):
            value = text[len(prefix):]
            return replacement + ENGLISH.get(value, value)
    for prefix, (suffix, template) in EXIT_MESSAGES.items():
        if text.startswith(prefix) and text.endswith(suffix):
            return template.format(text[len(prefix):-len(suffix)])
    return text
